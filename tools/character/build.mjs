// Builds the technician end to end, reproducibly: node tools/character/build.mjs
//   1. Blender: tools/blender/technician_v3.py (geometry, rig, atlas) into tools/character/out/ (not committed)
//   2. public/models/characters/technician-v3.glb, registered in the manifest and meshopt-compressed
//   3. public/models/characters/tex/*.webp at two sizes (encoded by Chrome, so no native image tooling is needed)
//   4. src/world/characters/rigData.generated.ts
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { chromium } from '@playwright/test';

const BLENDER = process.env.BLENDER ?? 'C:/Program Files/Blender Foundation/Blender 5.2/blender.exe';
const OUT = resolve('tools/character/out');
mkdirSync(OUT, { recursive: true });
if (!process.argv.includes('--skip-blender')) {
  const args = ['-b', '--factory-startup', '--python', 'tools/blender/technician_v3.py', '--', OUT];
  const log = execFileSync(BLENDER, args, { encoding: 'utf8', maxBuffer: 1 << 28 });
  if (!log.includes('BUILD OK')) throw new Error(`Blender did not finish:\n${log.slice(-3000)}`);
  writeFileSync(`${OUT}/build.log`, log);
}

// ---------------------------------------------------------------- rig table
const rig = JSON.parse(readFileSync(`${OUT}/rig.json`, 'utf8'));
const ts = `// Generated by tools/character/build.mjs from tools/blender/technician_v3.py. Do not edit.
export const RIG_ORDER = ${JSON.stringify(rig.order)} as const;
export type BoneName = (typeof RIG_ORDER)[number];
export const RIG_BONES: Record<BoneName, { parent: BoneName | null; at: [number, number, number]; bind: [number, number, number, number] }> = ${JSON.stringify(rig.bones)};
export const RIG_MEASURES = ${JSON.stringify(rig.measures)} as const;
`;
writeFileSync('src/world/characters/rigData.generated.ts', ts);

// ---------------------------------------------------------------- textures
mkdirSync('public/models/characters/tex', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage();
const encode = async (name, sizes, quality) => {
  for (const size of sizes) {
    const url = pathToFileURL(`${OUT}/technician-${name}.png`).href;
    await page.goto(url);
    const data = await page.evaluate(
      async ({ size, quality }) => {
        const img = document.querySelector('img');
        await img.decode();
        const c = document.createElement('canvas');
        c.width = c.height = size;
        const ctx = c.getContext('2d');
        ctx.imageSmoothingQuality = 'high';
        ctx.drawImage(img, 0, 0, size, size);
        return c.toDataURL('image/webp', quality);
      },
      { size, quality },
    );
    const file = `public/models/characters/tex/technician-${name}-${size}.webp`;
    writeFileSync(file, Buffer.from(data.split(',')[1], 'base64'));
    console.log(`${file}: ${(statSync(file).size / 1024).toFixed(0)} KB`);
  }
};
await encode('albedo', [2048, 1024], 0.9);
await encode('normal', [1024, 512], 0.92);
await encode('orm', [2048, 1024], 0.96);
await browser.close();

// ---------------------------------------------------------------- geometry
copyFileSync(`${OUT}/technician-v3.glb`, 'public/models/characters/technician-v3.glb');
execFileSync('node', ['tools/assets/register-blender.mjs', 'technician-v3', 'characters', 'tools/blender/technician_v3.py', 'EGO HVAC technician, generation 3: CC0 MakeHuman anatomy, garments as geometry, 43-bone rig, three levels of detail'], { stdio: 'inherit' });
console.log(`glb: ${(statSync('public/models/characters/technician-v3.glb').size / 1024).toFixed(0)} KB`);
